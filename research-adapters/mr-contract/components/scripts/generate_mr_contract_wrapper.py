#!/usr/bin/env python3
"""Render a manifest-hashed shell wrapper from the sole R method source."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / 'study_plugins/mr-contract/scripts'


def rendered():
    return ('# Generated by scripts/generate_mr_contract_wrapper.py; do not edit.\n'
        'set -eu\n'
        'exec Rscript --vanilla - "$AUTONOMICS_INPUT0" "$AUTONOMICS_INPUT1" '
        '"$AUTONOMICS_INPUT2" "$AUTONOMICS_INPUT3" "$AUTONOMICS_INPUT4" "$AUTONOMICS_INPUT5" "$AUTONOMICS_OUTPUT0" '
        '"$AUTONOMICS_OUTPUT1" "$AUTONOMICS_OUTPUT2" "$AUTONOMICS_OUTPUT3" '
        "<<'AUTONOMICS_FROZEN_MR_R'\n" + (ROOT.parents[1]/'shared/gwas-normalization-receipt.R').read_text() + '\n' +
        (ROOT / 'mr.R').read_text() + 'AUTONOMICS_FROZEN_MR_R\n')


if __name__ == '__main__':
    (ROOT / 'run-mr.sh').write_text(rendered())
