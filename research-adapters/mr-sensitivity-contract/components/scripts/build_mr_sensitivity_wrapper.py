#!/usr/bin/env python3
"""Bundle the original MR validator and sensitivity source into one loader script."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def render():
    parent = (ROOT / 'study_plugins/mr-contract/scripts/mr.R').read_text()
    marker = 'if (sys.nframe() == 0L) tryCatch(main(commandArgs(trailingOnly = TRUE)), error = function(e) {'
    if parent.count(marker) != 1:
        raise ValueError('parent R entry point changed; refuse partial bundle')
    # All original functions remain byte-for-byte. Remove only its standalone
    # dispatch, as the candidate supplies its own dispatch and argument schema.
    parent = parent.split(marker)[0]
    helper = (ROOT / 'study_plugins/shared/gwas-normalization-receipt.R').read_text()
    sensitivity = (ROOT / 'study_plugins/mr-sensitivity-contract/scripts/sensitivity.R').read_text()
    body = helper + '\n' + parent + '\n' + sensitivity
    return '#!/bin/sh\nset -eu\nSCRIPT=$(mktemp /tmp/autonomics-mr-sensitivity-XXXXXX.R)\ntrap \'rm -f "$SCRIPT"\' EXIT HUP INT TERM\ncat > "$SCRIPT" <<\'AUTONOMICS_FROZEN_MR_SENSITIVITY\'\n' + body + '\nAUTONOMICS_FROZEN_MR_SENSITIVITY\nRscript --vanilla "$SCRIPT" "$AUTONOMICS_INPUT0" "$AUTONOMICS_INPUT1" "$AUTONOMICS_INPUT2" "$AUTONOMICS_INPUT3" "$AUTONOMICS_INPUT4" "$AUTONOMICS_INPUT5" "$AUTONOMICS_INPUT6" "$AUTONOMICS_OUTPUT0" "$AUTONOMICS_OUTPUT1" "$AUTONOMICS_OUTPUT2" "$AUTONOMICS_OUTPUT3"\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Reject stale generated bytes without writing.')
    args = parser.parse_args()
    target = ROOT / 'study_plugins/mr-sensitivity-contract/scripts/run-sensitivity.sh'
    expected = render().encode()
    if args.check:
        if target.is_symlink() or not target.is_file() or target.read_bytes() != expected:
            raise SystemExit('Supporting MR wrapper is missing or stale; regenerate from the complete pinned sources.')
    else:
        target.write_bytes(expected)
        target.chmod(0o755)
