#!/usr/bin/env python3
"""Embed the sole clumping R source in a manifest-hashed vanilla wrapper."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / 'study_plugins/clump-contract/scripts'


def rendered():
    return ('# Generated by scripts/generate_clump_contract_wrapper.py; do not edit.\n'
        'set -eu\nexport LC_ALL=C\n'
        'exec Rscript --vanilla - "$AUTONOMICS_INPUT0" "$AUTONOMICS_INPUT1" '
        '"$AUTONOMICS_INPUT2" "$AUTONOMICS_INPUT3" "$AUTONOMICS_INPUT4" /panels/plink_ref /work/clump-execution '
        '"$AUTONOMICS_OUTPUT0" "$AUTONOMICS_OUTPUT1" "$AUTONOMICS_OUTPUT2" '
        '"$AUTONOMICS_OUTPUT3" "$AUTONOMICS_OUTPUT4" ' + "<<'AUTONOMICS_FROZEN_CLUMP_R'\n" +
        (ROOT.parents[1]/'shared/gwas-normalization-receipt.R').read_text() + '\n' +
        (ROOT/'clump.R').read_text() + 'AUTONOMICS_FROZEN_CLUMP_R\n')


if __name__ == '__main__':
    (ROOT/'run-clump.sh').write_text(rendered())
